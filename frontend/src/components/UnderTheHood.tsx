import { useState } from "react";

/**
 * The honesty panel: shows the LIVE Qiskit circuit diagram for whatever the
 * player just did. Every spell in the game is a real circuit — this panel is
 * the proof (and the thing to show skeptical judges).
 */
export default function UnderTheHood({ diagram }: { diagram: string | null }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="mt-4 rounded-xl border border-cyan-800/50 bg-black/20">
      <button
        className="w-full text-left px-4 py-2 text-sm text-cyan-300 hover:text-cyan-100 flex items-center gap-2"
        onClick={() => setOpen((o) => !o)}
      >
        <span>{open ? "▾" : "▸"}</span>
        <span>🔧 Under the hood — the real Qiskit circuit running right now</span>
      </button>
      {open && (
        <div className="px-4 pb-4">
          {diagram ? (
            <pre className="overflow-x-auto text-[10px] leading-[1.15] text-emerald-200/90 bg-black/40 rounded-lg p-3">
              {diagram}
            </pre>
          ) : (
            <p className="text-sm text-cyan-200/60">
              Cast a spell first — the circuit appears here.
            </p>
          )}
          <p className="text-xs text-cyan-200/50 mt-2">
            This diagram is generated by Qiskit from the exact circuit whose
            statevector you see in the bar chart. No JavaScript pretending.
          </p>
        </div>
      )}
    </div>
  );
}
